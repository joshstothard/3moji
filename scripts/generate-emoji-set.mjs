#!/usr/bin/env node
// Generates packages/core/src/emoji/emoji-candidates.generated.ts from the
// Emoji Set candidate report.
//
// The report is the source of truth for the pinned candidate list (ADR-0005),
// so the shipped data is derived from it rather than retyped. Releasing a new
// category does NOT need this script: that is a one-line edit to
// RELEASED_CATEGORIES in packages/core/src/emoji/emoji-category.ts, and the
// released flag is derived from it at runtime (ADR-0007 decision 5).
//
// Run with: npm run generate:emoji

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import prettier from "prettier";

const REPO_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);

export const CANDIDATE_REPORT = path.join(
  REPO_ROOT,
  "docs/reports/2026-09-11-emoji-set.candidates.json",
);

export const OUTPUT_FILE = path.join(
  REPO_ROOT,
  "packages/core/src/emoji/emoji-candidates.generated.ts",
);

/**
 * The Unicode groups the candidate list may use. Kept in step with
 * EMOJI_CATEGORIES in packages/core/src/emoji/emoji-category.ts; an unknown
 * group here would generate a module that does not typecheck, so fail loudly
 * instead.
 */
export const KNOWN_CATEGORIES = [
  "Activities",
  "Animals & Nature",
  "Food & Drink",
  "Objects",
  "People & Body",
  "Smileys & Emotion",
  "Symbols",
  "Travel & Places",
];

/**
 * Validates the report and projects it onto the EmojiCandidate shape.
 *
 * `group` becomes `category`: the domain calls it a category because it is the
 * unit a release drop uses, while the report keeps Unicode's own word.
 *
 * @param {unknown} report Parsed contents of the candidate report.
 * @returns {{codepoint: string, emoji: string, spokenName: string, category: string}[]}
 */
export function buildEntries(report) {
  if (!Array.isArray(report)) {
    throw new TypeError("Candidate report must be an array of entries.");
  }

  return report.map((entry, index) => {
    const where = `entry ${index}`;
    if (typeof entry !== "object" || entry === null) {
      throw new TypeError(`${where} is not an object.`);
    }

    const { codepoint, emoji, spokenName, group } = entry;
    for (const [field, value] of Object.entries({
      codepoint,
      emoji,
      spokenName,
      group,
    })) {
      if (typeof value !== "string" || value === "") {
        throw new TypeError(`${where} has a missing or non-string ${field}.`);
      }
    }

    if (!KNOWN_CATEGORIES.includes(group)) {
      throw new RangeError(`${where} has unknown group "${group}".`);
    }

    // ADR-0005 excludes sequences by construction. Assert it here as well as in
    // the domain test, so a bad report never reaches the shipped data.
    if ([...emoji].length !== 1) {
      throw new RangeError(
        `${where} (${codepoint}) is not a single code point.`,
      );
    }

    return { codepoint, emoji, spokenName, category: group };
  });
}

/**
 * Renders the generated TypeScript module. Formatted with the repo's Prettier
 * config so re-running the generator produces no phantom diff.
 *
 * @param {{codepoint: string, emoji: string, spokenName: string, category: string}[]} entries
 * @returns {Promise<string>}
 */
export async function renderModule(entries) {
  const body = entries
    .map(
      ({ codepoint, emoji, spokenName, category }) =>
        `  { codepoint: ${JSON.stringify(codepoint)}, emoji: ${JSON.stringify(emoji)}, spokenName: ${JSON.stringify(spokenName)}, category: ${JSON.stringify(category)} },`,
    )
    .join("\n");

  const source = `// Generated by scripts/generate-emoji-set.mjs — do not edit by hand.
// Source: docs/reports/2026-09-11-emoji-set.candidates.json (${entries.length} entries,
// the Emoji 12.0 candidate list pinned by ADR-0005).
// Run \`npm run generate:emoji\` to regenerate.
//
// Which of these are claimable is NOT decided here: RELEASED_CATEGORIES in
// ./emoji-category.ts decides that, so a category drop needs no regeneration.

import type { EmojiCandidate } from "./emoji-candidate";

export const emojiCandidates: readonly EmojiCandidate[] = [
${body}
];
`;

  const options = await prettier.resolveConfig(OUTPUT_FILE);
  return prettier.format(source, {
    ...options,
    filepath: OUTPUT_FILE,
  });
}

export async function generate() {
  const report = JSON.parse(await readFile(CANDIDATE_REPORT, "utf8"));
  const entries = buildEntries(report);
  await writeFile(OUTPUT_FILE, await renderModule(entries), "utf8");
  return entries.length;
}

// Importing this module (the script tests do) must not write files.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const count = await generate();
  console.log(
    `Wrote ${count} candidate emoji to ${path.relative(REPO_ROOT, OUTPUT_FILE)}`,
  );
}

#!/usr/bin/env node
// Generates apps/web/src/lib/og/emoji-glyphs.generated.ts: one SVG per emoji in
// the released Emoji Set, for the Profile's Open Graph image (#161).
//
// Why per-glyph SVGs and not a font: `next/og`'s ImageResponse draws text with
// satori, which cannot render a colour emoji font (CBDT/COLR), and whose only
// fallback for a missing glyph is to fetch one from a CDN at request time. The
// image draws each emoji as an <img> from this module instead, so rendering a
// Profile image makes no network request at all.
//
// The source is pinned to one commit of Twemoji. Its graphics are CC-BY 4.0;
// the licence text sits beside the generated module in
// apps/web/src/lib/og/TWEMOJI-LICENSE-GRAPHICS.txt and the attribution is in
// docs/architecture/system-overview.md § A Profile's Open Graph card.
//
// Only the released categories are generated. A category drop (a one-line edit
// to RELEASED_CATEGORIES) therefore needs this script re-run, and
// apps/web/src/lib/og/glyphs.test.ts fails until it is.
//
// Run with: node scripts/generate-og-glyphs.mjs   (needs network access to GitHub)

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import prettier from "prettier";

const REPO_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);

export const CANDIDATE_REPORT = path.join(
  REPO_ROOT,
  "docs/reports/2026-09-11-emoji-set.candidates.json",
);

export const CATEGORY_MODULE = path.join(
  REPO_ROOT,
  "packages/core/src/emoji/emoji-category.ts",
);

export const OUTPUT_FILE = path.join(
  REPO_ROOT,
  "apps/web/src/lib/og/emoji-glyphs.generated.ts",
);

/** Twemoji (the maintained jdecked fork), tag v16.0.1. */
export const TWEMOJI_VERSION = "16.0.1";
export const TWEMOJI_COMMIT = "50c7abfe6813680455781862f7b34305cd1eb9f5";

/** How many glyphs are fetched at once. */
const FETCH_BATCH = 20;

/**
 * The file name Twemoji gives a single-code-point emoji: its lower-case hex.
 *
 * @param {string} codepoint `U+1F9CA` form, as the candidate report spells it.
 * @returns {string}
 */
export function twemojiFileOf(codepoint) {
  const match = /^U\+([0-9A-F]{4,6})$/.exec(codepoint);
  if (match === null) {
    throw new RangeError(`"${codepoint}" is not a U+XXXX code point.`);
  }
  return `${match[1].toLowerCase()}.svg`;
}

/**
 * The released categories, read from the domain module that decides them, so
 * this script cannot drift from `RELEASED_CATEGORIES`.
 *
 * @param {string} source Contents of emoji-category.ts.
 * @returns {string[]}
 */
export function releasedCategoriesFrom(source) {
  const block = /export const RELEASED_CATEGORIES[^=]*=\s*\[([^\]]*)\]/.exec(
    source,
  );
  if (block === null) {
    throw new Error("RELEASED_CATEGORIES was not found in emoji-category.ts.");
  }
  return [...block[1].matchAll(/"([^"]+)"/g)].map((match) => match[1]);
}

/**
 * The released entries of the candidate report, in report order.
 *
 * @param {unknown} report Parsed candidate report.
 * @param {string[]} released Released category names.
 * @returns {{codepoint: string, emoji: string}[]}
 */
export function releasedEntries(report, released) {
  if (!Array.isArray(report)) {
    throw new TypeError("Candidate report must be an array of entries.");
  }
  return report
    .filter((entry) => released.includes(entry.group))
    .map(({ codepoint, emoji }) => {
      if ([...emoji].length !== 1) {
        throw new RangeError(`${codepoint} is not a single code point.`);
      }
      return { codepoint, emoji };
    });
}

/**
 * An SVG is embedded only if it is a self-contained drawing: no script, no
 * external reference, nothing a renderer could be made to fetch.
 *
 * @param {string} codepoint
 * @param {string} svg
 * @returns {string}
 */
export function checkedSvg(codepoint, svg) {
  if (!svg.startsWith("<svg ")) {
    throw new Error(`${codepoint}: not an SVG document.`);
  }
  if (/<script|<image|<foreignObject|href|url\(|@import/i.test(svg)) {
    throw new Error(`${codepoint}: SVG references something outside itself.`);
  }
  return svg.trim();
}

/**
 * @param {{emoji: string, svg: string}[]} glyphs
 * @returns {Promise<string>}
 */
export async function renderModule(glyphs) {
  const body = glyphs
    .map(
      ({ emoji, svg }) =>
        `  [${JSON.stringify(emoji)}, ${JSON.stringify(svg)}],`,
    )
    .join("\n");

  const source = `// Generated by scripts/generate-og-glyphs.mjs — do not edit by hand.
// Run \`node scripts/generate-og-glyphs.mjs\` to regenerate.
//
// ${glyphs.length} emoji graphics from Twemoji ${TWEMOJI_VERSION}
// (https://github.com/jdecked/twemoji, commit ${TWEMOJI_COMMIT}),
// copyright Twitter, Inc. and other contributors, and jdecked and other
// contributors, licensed under CC-BY 4.0
// (https://creativecommons.org/licenses/by/4.0/). The licence text is in
// ./TWEMOJI-LICENSE-GRAPHICS.txt. The SVGs are unmodified.

/** Each released emoji, mapped to its Twemoji SVG document. */
export const EMOJI_GLYPHS: ReadonlyMap<string, string> = new Map([
${body}
]);
`;

  const options = await prettier.resolveConfig(OUTPUT_FILE);
  return prettier.format(source, { ...options, filepath: OUTPUT_FILE });
}

export async function generate() {
  const [report, categories] = await Promise.all([
    readFile(CANDIDATE_REPORT, "utf8").then((text) => JSON.parse(text)),
    readFile(CATEGORY_MODULE, "utf8"),
  ]);
  const entries = releasedEntries(report, releasedCategoriesFrom(categories));

  // In batches: hundreds of simultaneous connections to one host time out.
  const glyphs = [];
  for (let start = 0; start < entries.length; start += FETCH_BATCH) {
    const batch = entries.slice(start, start + FETCH_BATCH);
    glyphs.push(
      ...(await Promise.all(
        batch.map(async ({ codepoint, emoji }) => {
          const url = `https://raw.githubusercontent.com/jdecked/twemoji/${TWEMOJI_COMMIT}/assets/svg/${twemojiFileOf(codepoint)}`;
          const response = await fetch(url);
          if (!response.ok) {
            throw new Error(
              `${codepoint}: ${String(response.status)} from ${url}`,
            );
          }
          return { emoji, svg: checkedSvg(codepoint, await response.text()) };
        }),
      )),
    );
  }

  await writeFile(OUTPUT_FILE, await renderModule(glyphs), "utf8");
  return glyphs.length;
}

// Importing this module (the script tests do) must not fetch or write files.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const count = await generate();
  console.log(
    `Wrote ${count} emoji glyphs to ${path.relative(REPO_ROOT, OUTPUT_FILE)}`,
  );
}
